def build_user_message(
    product: ProductInput,
    previous_draft: LlmDraft | None,
    problems: list[str],
) -> str:
    message = f"Данные о товаре:\n<product>\n{product.model_dump_json(indent=2)}\n</product>"
    if previous_draft is None:
        return message

    problem_list = "\n".join(f"- {problem}" for problem in problems)
    return (
        f"{message}\n\nПредыдущий черновик:\n<draft>\n{previous_draft.model_dump_json(indent=2)}\n"
        f"</draft>\n\nАвтоматическая проверка нашла проблемы:\n{problem_list}\n\n"
        "Исправь черновик и верни его целиком. Убери всё, чего нет в данных о товаре. "
        "Если описание короче нормы, раскрой факты из данных, которые ещё не использованы."
    )
